import type { DrillLine, DrillMove, DrillMoveAlert } from '@/lib/drills/types'

/**
 * Caro-Kann drills. Fun traps from
 * https://www.youtube.com/watch?v=TtFni8eegEE come first, then named
 * theory from the Lichess opening book (lichess-org/chess-openings).
 *
 * Play rate, win rate, and the computer's best move are not stored here.
 * The drill asks the opener for them with whatever filters are selected.
 */

function ply(
  san: string,
  hint: string,
  opts?: DrillMoveAlert | { revealIdea: true },
): DrillMove {
  if (!opts) return { san, hint }
  if ('revealIdea' in opts) return { san, hint, revealIdea: true }
  return { san, hint, alert: opts }
}

function line(
  id: string,
  name: string,
  summary: string,
  eco: string,
  moves: DrillMove[],
): DrillLine {
  return {
    id,
    name,
    summary,
    eco,
    family: 'caro-kann',
    side: 'black',
    opening: 'caro-kann',
    moves,
  }
}

